#!/usr/bin/env node
/*
 * scripts/build-dictionary-data.js — derives the runtime dictionary files
 * from the source shards.
 *
 * SOURCE (edited by people and by the ingestion pipeline, never shipped to
 * the browser any more): js/data.<lang>[.<shard>].js, listed in
 * js/dictionary-manifest.js.
 *
 * DERIVED (generated here, committed, what the app actually loads):
 *
 *   js/dict.<lang>.idx.<n>.js   INDEX shards — one row per entry with only
 *                               what the list, the search, the alphabet, the
 *                               topic filters, the word of the day and the
 *                               "which word is it?" game need:
 *                               [id, word, definition, synonyms, imageId, topic].
 *   js/dict.<lang>.det.<kkk>.js DETAIL chunks — the heavy fields (pictogram
 *                               alt text, both example sentences and the
 *                               already resolved translation links), keyed
 *                               by id. An entry lives in chunk
 *                               fnv1a(id) % chunks, so the browser can find
 *                               it from the id alone.
 *   js/dictionary-data.js       the runtime manifest: every derived file with
 *                               its content-hash `?v=` URL. Read by
 *                               js/dictionary-loader.js AND by sw.js
 *                               (importScripts), which uses it to keep the
 *                               whole dictionary available offline.
 *
 * Usage:
 *   node scripts/build-dictionary-data.js          regenerate everything
 *   node scripts/check.js                          fails if anything is stale
 *
 * Run it after ANY change to a js/data.*.js file (including ingestion
 * batches). It also refreshes the `?v=` hashes of the source manifest.
 *
 * Translation links are resolved here, once, with the same rules the app
 * used to apply at run time (see resolveTranslations), so the app never
 * needs the other language's dictionary just to draw a "see it in English"
 * link.
 */

"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const JS_DIR = path.join(ROOT, "js");

// Tuning knobs. Changing either one regenerates every derived file.
const INDEX_ROWS_PER_SHARD = 20000;
const DETAIL_CHUNKS = 128;

// Fields the source entries may have. Anything else is a hard error so a new
// field can never be silently dropped from the runtime files.
const KNOWN_FIELDS = new Set([
  "id", "word", "image", "definition", "synonyms",
  "example", "exampleSynonym", "situacion", "translation",
]);

const GENERATED_HEADER =
  "/* Generated by scripts/build-dictionary-data.js from js/data.*.js. Do not edit. */\n";

function contentHash(content) {
  return crypto.createHash("sha256").update(content).digest("hex").slice(0, 10);
}

// Same function as js/dictionary-loader.js#chunkOf. Keep them identical.
function chunkOf(id, chunks) {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i += 1) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0) % chunks;
}

function pad3(n) {
  return String(n).padStart(3, "0");
}

// --- Translation links -----------------------------------------------------
// Resolved in two passes, per other language:
//
// 1. EXPLICIT: the entry has `translation[lang]` (id or array of ids). Those
//    ids win, and when the field exists for a language no implicit guess is
//    made for it. Ids that do not exist are skipped.
// 2. IMPLICIT (fallback): link when the entry's pictogram is unique among the
//    entries of its own language AND exactly one entry of the other language
//    uses the same pictogram.
//
// If neither pass finds anything, no link: better none than a wrong one.
function resolveTranslations(dictionaries) {
  const languages = Object.keys(dictionaries);
  const byId = {};
  const imageCount = {};
  const imageFirst = {};
  languages.forEach(function (lang) {
    byId[lang] = new Map();
    imageCount[lang] = new Map();
    imageFirst[lang] = new Map();
    dictionaries[lang].forEach(function (entry) {
      byId[lang].set(entry.id, entry);
      const imageId = entry.image.id;
      imageCount[lang].set(imageId, (imageCount[lang].get(imageId) || 0) + 1);
      if (!imageFirst[lang].has(imageId)) imageFirst[lang].set(imageId, entry);
    });
  });

  return function translationsOf(language, entry) {
    const links = [];
    languages.forEach(function (other) {
      if (other === language) return;
      if (entry.translation && entry.translation[other]) {
        const declared = entry.translation[other];
        (Array.isArray(declared) ? declared : [declared]).forEach(function (otherId) {
          const target = byId[other].get(otherId);
          if (target) links.push([other, target.id, target.word]);
        });
        return;
      }
      if (imageCount[language].get(entry.image.id) !== 1) return;
      if (imageCount[other].get(entry.image.id) === 1) {
        const target = imageFirst[other].get(entry.image.id);
        links.push([other, target.id, target.word]);
      }
    });
    return links;
  };
}

// --- Build -----------------------------------------------------------------
// `dictionaries` is { es: [...entries], en: [...] } (the merged DICCIONARIOS).
// Returns every derived file as { path, content } plus the manifest source.
function build(dictionaries) {
  const languages = Object.keys(dictionaries);
  const translationsOf = resolveTranslations(dictionaries);
  const files = [];
  const manifest = { chunks: DETAIL_CHUNKS, images: [], imagesBytes: 0, languages: {} };
  const imageIds = new Set();

  languages.forEach(function (lang) {
    const entries = dictionaries[lang];
    const indexShards = [];
    const detailChunks = [];
    for (let k = 0; k < DETAIL_CHUNKS; k += 1) detailChunks.push({});

    entries.forEach(function (entry, position) {
      Object.keys(entry).forEach(function (field) {
        if (!KNOWN_FIELDS.has(field)) {
          throw new Error(lang + "/" + entry.id + ": unknown field \"" + field +
            "\" — teach scripts/build-dictionary-data.js and js/dictionary-loader.js about it");
        }
      });

      imageIds.add(entry.image.id);

      const shard = Math.floor(position / INDEX_ROWS_PER_SHARD);
      if (!indexShards[shard]) indexShards[shard] = [];
      indexShards[shard].push([
        entry.id, entry.word, entry.definition, entry.synonyms, entry.image.id, entry.situacion,
      ]);

      const record = [
        entry.image.alt,
        entry.example.word, entry.example.text,
        entry.exampleSynonym.word, entry.exampleSynonym.text,
      ];
      const links = translationsOf(lang, entry);
      if (links.length > 0) record.push(links);
      detailChunks[chunkOf(entry.id, DETAIL_CHUNKS)][entry.id] = record;
    });

    const langManifest = { count: entries.length, index: [], detail: [] };

    indexShards.forEach(function (rows, i) {
      const file = "js/dict." + lang + ".idx." + (i + 1) + ".js";
      const content = GENERATED_HEADER +
        "SinonimiaDictionary.defineIndex(" + JSON.stringify(lang) + "," + (i + 1) + "," +
        JSON.stringify(rows) + ");\n";
      files.push({ path: file, content: content });
      langManifest.index.push({ file: file, src: file + "?v=" + contentHash(content) });
    });

    detailChunks.forEach(function (records, k) {
      const file = "js/dict." + lang + ".det." + pad3(k) + ".js";
      const content = GENERATED_HEADER +
        "SinonimiaDictionary.defineDetail(" + JSON.stringify(lang) + "," + k + "," +
        JSON.stringify(records) + ");\n";
      files.push({ path: file, content: content });
      langManifest.detail.push({ file: file, src: file + "?v=" + contentHash(content) });
    });

    manifest.languages[lang] = langManifest;
  });

  // Every pictogram any entry uses (img/<id>.png), for the optional offline
  // copy. The byte total only sizes the "save the drawings" offer in the UI.
  manifest.images = Array.from(imageIds).sort(function (a, b) { return a - b; });
  manifest.images.forEach(function (id) {
    const file = path.join(ROOT, "img", id + ".png");
    if (fs.existsSync(file)) manifest.imagesBytes += imageBytes(file);
  });

  return { files: files, manifestSource: renderManifest(manifest), manifest: manifest };
}

// Real size of a pictogram. A checkout without Git LFS (CI) holds a small
// pointer file instead of the PNG; its "size" line is the real size, so the
// generated manifest is the same with or without LFS.
function imageBytes(file) {
  const size = fs.statSync(file).size;
  if (size > 1024) return size;
  const pointer = fs.readFileSync(file, "utf8");
  const match = /^version https:\/\/git-lfs\.github\.com\/spec\/v1\r?\n[\s\S]*^size (\d+)$/m.exec(pointer);
  return match ? Number(match[1]) : size;
}

function renderManifest(manifest) {
  const lines = [];
  lines.push("/*");
  lines.push(" * Sinonimia runtime dictionary manifest. GENERATED by");
  lines.push(" * scripts/build-dictionary-data.js — do not edit by hand.");
  lines.push(" *");
  lines.push(" * Lists every derived dictionary file with its content-hash `?v=` URL, plus the");
  lines.push(" * ids of every pictogram in use (`images`) for the optional offline copy.");
  lines.push(" * Loaded by index.html/404.html (js/dictionary-loader.js) and by sw.js");
  lines.push(" * (importScripts), which downloads the whole list in the background so the");
  lines.push(" * app works offline. `globalThis` because a service worker has no `window`.");
  lines.push(" */");
  lines.push("globalThis.SINONIMIA_DICTIONARY_DATA = {");
  lines.push("  chunks: " + manifest.chunks + ",");
  lines.push("  imagesBytes: " + manifest.imagesBytes + ",");
  lines.push("  images: [");
  for (let i = 0; i < manifest.images.length; i += 16) {
    lines.push("    " + manifest.images.slice(i, i + 16).join(", ") + ",");
  }
  lines.push("  ],");
  lines.push("  languages: {");
  Object.keys(manifest.languages).forEach(function (lang, li, all) {
    const l = manifest.languages[lang];
    lines.push("    " + JSON.stringify(lang) + ": {");
    lines.push("      count: " + l.count + ",");
    ["index", "detail"].forEach(function (kind, ki) {
      lines.push("      " + kind + ": [");
      l[kind].forEach(function (shard) {
        lines.push("        " + JSON.stringify(shard) + ",");
      });
      lines.push("      ]" + (ki === 0 ? "," : ""));
    });
    lines.push("    }" + (li < all.length - 1 ? "," : ""));
  });
  lines.push("  },");
  lines.push("};");
  return lines.join("\n") + "\n";
}

// Loads the source shards listed in js/dictionary-manifest.js into one merged
// { lang: entries } object (same contract the shards have in the browser).
function loadSourceDictionaries() {
  const ctx = {};
  ctx.window = ctx;
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(JS_DIR, "dictionary-manifest.js"), "utf8"), ctx);
  const manifest = ctx.SINONIMIA_DICTIONARY_SHARDS;
  Object.keys(manifest).forEach(function (lang) {
    manifest[lang].forEach(function (shard) {
      vm.runInContext(fs.readFileSync(path.join(ROOT, shard.file), "utf8"), ctx, { filename: shard.file });
    });
  });
  return ctx.DICCIONARIOS;
}

// Rewrites the `?v=<hash>` of every source shard in js/dictionary-manifest.js.
function refreshSourceManifest() {
  const manifestPath = path.join(JS_DIR, "dictionary-manifest.js");
  let text = fs.readFileSync(manifestPath, "utf8");
  text = text.replace(/(js\/data\.[a-z0-9.-]+\.js)\?v=[a-f0-9]{10}/g, function (match, file) {
    return file + "?v=" + contentHash(fs.readFileSync(path.join(ROOT, file)));
  });
  fs.writeFileSync(manifestPath, text);
}

function main() {
  const started = Date.now();
  const dictionaries = loadSourceDictionaries();
  const result = build(dictionaries);

  const keep = new Set(result.files.map(function (f) { return f.path; }));
  fs.readdirSync(JS_DIR).forEach(function (name) {
    if (/^dict\..+\.js$/.test(name) && !keep.has("js/" + name)) {
      fs.unlinkSync(path.join(JS_DIR, name));
    }
  });

  let written = 0;
  result.files.forEach(function (file) {
    const target = path.join(ROOT, file.path);
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== file.content) {
      fs.writeFileSync(target, file.content);
      written += 1;
    }
  });
  fs.writeFileSync(path.join(JS_DIR, "dictionary-data.js"), result.manifestSource);
  refreshSourceManifest();

  const languages = Object.keys(result.manifest.languages).map(function (lang) {
    return lang + ": " + result.manifest.languages[lang].count + " entries";
  });
  console.log("Dictionary data built (" + languages.join(", ") + "): " +
    result.files.length + " files, " + written + " rewritten, " +
    ((Date.now() - started) / 1000).toFixed(1) + "s.");
  console.log("Remember: bump VERSION in sw.js (js/dictionary-data.js changed).");
}

module.exports = { build: build, chunkOf: chunkOf, contentHash: contentHash, DETAIL_CHUNKS: DETAIL_CHUNKS };

if (require.main === module) main();
